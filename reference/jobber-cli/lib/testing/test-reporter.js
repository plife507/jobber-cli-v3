/**
 * Purpose: Test Report Generation - creates JSON and Markdown reports from API verification test results
 * Inputs: Test results object with query successes/failures, throttle statistics, relationship data
 * Outputs: JSON report files, Markdown summary documents with statistics and examples
 * Dependencies: fs, path, logger
 */

import fs from 'fs';
import path from 'path';
import logger from '../utils/logger.js';

export class TestReporter {
  constructor(options = {}) {
    this.outputDir = options.outputDir || path.join(process.cwd(), 'docs');
    this.timestamp = new Date().toISOString().replace(/[:.]/g, '-');
  }

  /**
   * Generate comprehensive test report
   * @param {Object} testResults - Complete test results object
   * @returns {Object} Paths to generated reports
   */
  generateReports(testResults) {
    const jsonPath = this.generateJsonReport(testResults);
    const summaryPath = this.generateSummaryMarkdown(testResults);
    const examplesPath = this.generateQueryExamplesMarkdown(testResults);
    const relationshipsPath = this.generateRelationshipsMarkdown(testResults);

    return {
      json: jsonPath,
      summary: summaryPath,
      examples: examplesPath,
      relationships: relationshipsPath
    };
  }

  /**
   * Generate JSON report with complete test results
   * @param {Object} testResults - Test results
   * @returns {string} Path to JSON report
   */
  generateJsonReport(testResults) {
    const filename = `api_test_results_${this.timestamp}.json`;
    const filepath = path.join(this.outputDir, filename);

    const report = {
      metadata: {
        timestamp: new Date().toISOString(),
        version: '1.0.0',
        testDuration: testResults.duration || 0
      },
      summary: this._calculateSummary(testResults),
      throttleStats: testResults.throttleStats || {},
      phases: testResults.phases || {},
      queries: testResults.queries || [],
      failures: testResults.failures || [],
      relationships: testResults.relationships || []
    };

    fs.writeFileSync(filepath, JSON.stringify(report, null, 2), 'utf8');
    logger.success(`JSON report saved: ${filepath}`);

    return filepath;
  }

  /**
   * Generate Markdown summary document
   * @param {Object} testResults - Test results
   * @returns {string} Path to summary markdown
   */
  generateSummaryMarkdown(testResults) {
    const filepath = path.join(this.outputDir, 'API_TEST_RESULTS.md');
    const summary = this._calculateSummary(testResults);

    const markdown = `# Jobber API Test Results

**Generated:** ${new Date().toISOString()}  
**Test Duration:** ${this._formatDuration(testResults.duration || 0)}

## Summary

- **Total Queries Tested:** ${summary.totalTests}
- **Successful:** ${summary.successful} (${summary.successRate}%)
- **Failed:** ${summary.failed}
- **Skipped:** ${summary.skipped}

### Query Types

- **Connection Queries:** ${summary.connectionQueries.tested}/${summary.connectionQueries.total} tested (${summary.connectionQueries.successful} successful)
- **Single Object Queries:** ${summary.singleObjectQueries.tested}/${summary.singleObjectQueries.total} tested (${summary.singleObjectQueries.successful} successful)

## Throttle Statistics

- **Total Throttle Units Used:** ${testResults.throttleStats?.totalUnitsUsed || 0}
- **Average Cost per Query:** ${testResults.throttleStats?.avgCostPerQuery?.toFixed(2) || 0}
- **Throttle Waits:** ${testResults.throttleStats?.waitCount || 0} (${this._formatDuration(testResults.throttleStats?.totalWaitTime || 0)})
- **Throttle Compliance:** ${testResults.throttleStats?.violations || 0} violations

## Phase Results

${this._generatePhaseResults(testResults.phases || {})}

## Top Failures

${this._generateTopFailures(testResults.failures || [])}

## Recommendations

${this._generateRecommendations(summary, testResults)}

---
*Generated by Jobber API Verification Testing Suite*
`;

    fs.writeFileSync(filepath, markdown, 'utf8');
    logger.success(`Summary report saved: ${filepath}`);

    return filepath;
  }

  /**
   * Generate query examples markdown document
   * @param {Object} testResults - Test results
   * @returns {string} Path to examples markdown
   */
  generateQueryExamplesMarkdown(testResults) {
    const filepath = path.join(this.outputDir, 'API_QUERY_EXAMPLES.md');
    const successfulQueries = (testResults.queries || []).filter(q => q.success);

    // Group by query type
    const connectionQueries = successfulQueries.filter(q => q.type === 'connection');
    const singleObjectQueries = successfulQueries.filter(q => q.type === 'single');

    const markdown = `# Jobber API Query Examples

**Generated:** ${new Date().toISOString()}

This document contains working query examples verified against the Jobber GraphQL API.

## Table of Contents

- [Connection Queries](#connection-queries) (${connectionQueries.length})
- [Single Object Queries](#single-object-queries) (${singleObjectQueries.length})

---

## Connection Queries

Connection queries return paginated lists of entities with \`edges\` and \`pageInfo\`.

${this._generateQueryExamples(connectionQueries)}

---

## Single Object Queries

Single object queries return a specific entity by ID.

${this._generateQueryExamples(singleObjectQueries)}

---

## Usage Notes

### Pagination Pattern

All connection queries support pagination with these arguments:

\`\`\`graphql
{
  queryName(first: 10, after: "cursor") {
    edges {
      node { id }
      cursor
    }
    pageInfo {
      hasNextPage
      endCursor
    }
  }
}
\`\`\`

### Throttle Management

- Always check throttle status before making queries
- Estimated costs range from ${this._getMinCost(testResults)} to ${this._getMaxCost(testResults)} units
- Connection queries typically cost 50-200 units
- Complex nested queries can cost 500+ units

### Best Practices

1. **Start with minimal fields** - Request only what you need
2. **Use pagination** - Don't fetch all data at once
3. **Batch related queries** - Reduce round trips
4. **Cache results** - Avoid redundant queries
5. **Monitor throttle budget** - Respect rate limits

---
*Generated by Jobber API Verification Testing Suite*
`;

    fs.writeFileSync(filepath, markdown, 'utf8');
    logger.success(`Query examples saved: ${filepath}`);

    return filepath;
  }

  /**
   * Generate relationships markdown document
   * @param {Object} testResults - Test results
   * @returns {string} Path to relationships markdown
   */
  generateRelationshipsMarkdown(testResults) {
    const filepath = path.join(this.outputDir, 'API_RELATIONSHIPS.md');
    const relationships = testResults.relationships || [];

    const markdown = `# Jobber API Relationships

**Generated:** ${new Date().toISOString()}

This document maps relationships between Jobber API types based on verified queries.

## Relationship Graph

${this._generateRelationshipGraph(relationships)}

## Verified Relationships

${this._generateRelationshipDetails(relationships)}

## Common Traversal Patterns

${this._generateTraversalPatterns(relationships)}

## Nested Query Examples

${this._generateNestedQueryExamples(relationships)}

---
*Generated by Jobber API Verification Testing Suite*
`;

    fs.writeFileSync(filepath, markdown, 'utf8');
    logger.success(`Relationships document saved: ${filepath}`);

    return filepath;
  }

  /**
   * Calculate summary statistics from test results
   * @private
   */
  _calculateSummary(testResults) {
    const queries = testResults.queries || [];
    const successful = queries.filter(q => q.success).length;
    const failed = queries.filter(q => !q.success && !q.skipped).length;
    const skipped = queries.filter(q => q.skipped).length;
    const total = queries.length;

    const connectionQueries = queries.filter(q => q.type === 'connection');
    const singleObjectQueries = queries.filter(q => q.type === 'single');

    return {
      totalTests: total,
      successful,
      failed,
      skipped,
      successRate: total > 0 ? ((successful / total) * 100).toFixed(2) : 0,
      connectionQueries: {
        total: testResults.totalConnectionQueries || connectionQueries.length,
        tested: connectionQueries.length,
        successful: connectionQueries.filter(q => q.success).length
      },
      singleObjectQueries: {
        total: testResults.totalSingleObjectQueries || singleObjectQueries.length,
        tested: singleObjectQueries.length,
        successful: singleObjectQueries.filter(q => q.success).length
      }
    };
  }

  /**
   * Generate phase results markdown section
   * @private
   */
  _generatePhaseResults(phases) {
    if (!phases || Object.keys(phases).length === 0) {
      return '*No phase data available*';
    }

    let markdown = '';
    Object.entries(phases).forEach(([phaseName, phaseData]) => {
      markdown += `### ${phaseName}\n\n`;
      markdown += `- **Duration:** ${this._formatDuration(phaseData.duration || 0)}\n`;
      markdown += `- **Tests:** ${phaseData.tests || 0}\n`;
      markdown += `- **Success Rate:** ${phaseData.successRate || 0}%\n`;
      markdown += `- **Throttle Cost:** ${phaseData.throttleCost || 0} units\n\n`;
    });

    return markdown;
  }

  /**
   * Generate top failures section
   * @private
   */
  _generateTopFailures(failures) {
    if (!failures || failures.length === 0) {
      return '*No failures recorded*';
    }

    const topFailures = failures.slice(0, 10);
    let markdown = '';

    topFailures.forEach((failure, index) => {
      markdown += `### ${index + 1}. ${failure.queryName}\n\n`;
      markdown += `- **Error:** ${failure.error}\n`;
      markdown += `- **Type:** ${failure.type || 'unknown'}\n`;
      if (failure.suggestion) {
        markdown += `- **Suggestion:** ${failure.suggestion}\n`;
      }
      markdown += '\n';
    });

    return markdown;
  }

  /**
   * Generate query examples markdown section
   * @private
   */
  _generateQueryExamples(queries) {
    if (!queries || queries.length === 0) {
      return '*No examples available*';
    }

    let markdown = '';

    queries.forEach((query, index) => {
      markdown += `### ${index + 1}. ${query.name}\n\n`;
      
      if (query.description) {
        markdown += `${query.description}\n\n`;
      }

      markdown += '```graphql\n';
      markdown += query.query || 'Query not available';
      markdown += '\n```\n\n';

      if (query.estimatedCost) {
        markdown += `**Estimated Cost:** ${query.estimatedCost} units\n\n`;
      }

      markdown += '---\n\n';
    });

    return markdown;
  }

  /**
   * Generate relationship graph
   * @private
   */
  _generateRelationshipGraph(relationships) {
    if (!relationships || relationships.length === 0) {
      return '*No relationships mapped*';
    }

    let markdown = '```\n';
    
    // Group by source type
    const grouped = {};
    relationships.forEach(rel => {
      if (!grouped[rel.from]) {
        grouped[rel.from] = [];
      }
      grouped[rel.from].push(rel.to);
    });

    Object.entries(grouped).forEach(([from, tos]) => {
      markdown += `${from}\n`;
      tos.forEach((to, index) => {
        const isLast = index === tos.length - 1;
        markdown += `  ${isLast ? '└─' : '├─'} ${to}\n`;
      });
    });

    markdown += '```\n';
    return markdown;
  }

  /**
   * Generate relationship details
   * @private
   */
  _generateRelationshipDetails(relationships) {
    if (!relationships || relationships.length === 0) {
      return '*No relationships available*';
    }

    let markdown = '';

    relationships.forEach((rel, index) => {
      markdown += `### ${rel.from} → ${rel.to}\n\n`;
      markdown += `- **Field:** ${rel.field}\n`;
      markdown += `- **Type:** ${rel.relationshipType || 'unknown'}\n`;
      if (rel.verified) {
        markdown += `- **Status:** ✅ Verified\n`;
      }
      markdown += '\n';
    });

    return markdown;
  }

  /**
   * Generate traversal patterns
   * @private
   */
  _generateTraversalPatterns(relationships) {
    return `
### Common Patterns

1. **Job → Client → Properties**
   - Access all properties for a job's client
   
2. **Client → Jobs → LineItems**
   - Get all line items across all jobs for a client
   
3. **Visit → Job → Invoice**
   - Link visit work to invoicing

4. **User → Account → Settings**
   - Access user and account configuration

*(More patterns discovered during testing)*
`;
  }

  /**
   * Generate nested query examples
   * @private
   */
  _generateNestedQueryExamples(relationships) {
    return `
### Example: Deep Nested Query

\`\`\`graphql
{
  job(id: "12345") {
    id
    title
    client {
      id
      name
      properties {
        edges {
          node {
            id
            address
          }
        }
      }
    }
    lineItems {
      edges {
        node {
          id
          name
          quantity
        }
      }
    }
  }
}
\`\`\`

*(Additional examples from verified relationships)*
`;
  }

  /**
   * Generate recommendations based on test results
   * @private
   */
  _generateRecommendations(summary, testResults) {
    const recommendations = [];

    if (parseFloat(summary.successRate) < 80) {
      recommendations.push('- **Low success rate**: Review failed queries and update schema mapping');
    }

    if (testResults.throttleStats?.violations > 0) {
      recommendations.push('- **Throttle violations detected**: Increase wait times between queries');
    }

    if (summary.failed > summary.successful) {
      recommendations.push('- **More failures than successes**: Verify API token and schema version');
    }

    if (recommendations.length === 0) {
      recommendations.push('- ✅ All tests performing well');
      recommendations.push('- Continue monitoring throttle usage');
      recommendations.push('- Update tests when API schema changes');
    }

    return recommendations.join('\n');
  }

  /**
   * Format duration in human-readable format
   * @private
   */
  _formatDuration(milliseconds) {
    const seconds = Math.floor(milliseconds / 1000);
    if (seconds < 60) return `${seconds}s`;
    
    const minutes = Math.floor(seconds / 60);
    const remainingSeconds = seconds % 60;
    return `${minutes}m ${remainingSeconds}s`;
  }

  /**
   * Get minimum cost from test results
   * @private
   */
  _getMinCost(testResults) {
    const queries = testResults.queries || [];
    if (queries.length === 0) return 0;
    
    const costs = queries.filter(q => q.estimatedCost).map(q => q.estimatedCost);
    return costs.length > 0 ? Math.min(...costs) : 0;
  }

  /**
   * Get maximum cost from test results
   * @private
   */
  _getMaxCost(testResults) {
    const queries = testResults.queries || [];
    if (queries.length === 0) return 0;
    
    const costs = queries.filter(q => q.estimatedCost).map(q => q.estimatedCost);
    return costs.length > 0 ? Math.max(...costs) : 0;
  }
}

export default TestReporter;

